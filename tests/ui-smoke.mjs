import {mkdirSync} from 'node:fs';
mkdirSync('test-results',{recursive:true});
import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/#/workspace?mode=sample',{waitUntil:'networkidle'});
await page.screenshot({path:'test-results/second-feature-desktop.png',fullPage:true});
assert.equal(await page.locator('h1').count(),1);
assert.equal(await page.getByRole('button',{name:'Inspect evidence',exact:true}).count(),1);
await page.getByRole('button',{name:'Inspect evidence',exact:true}).click();
await page.getByRole('heading',{name:'Show your working.'}).waitFor();
await page.keyboard.press('Escape');
const oldFilm=await page.locator('.companion-card h3').innerText();
await page.getByRole('button',{name:'Film unavailable? Re-plan',exact:true}).click();
await expect(page.locator('.companion-card h3')).toHaveCount(1);
assert.notEqual(await page.locator('.companion-card h3').innerText(),oldFilm);
await page.getByRole('button',{name:'Core',exact:true}).click();
assert.equal(await page.getByRole('button',{name:'Core',exact:true}).getAttribute('aria-pressed'),'true');
await page.getByRole('button',{name:'Review event brief'}).click();
await page.getByRole('textbox',{name:'Event title',exact:true}).fill('A night to remember');
const download=page.waitForEvent('download');await page.getByRole('button',{name:'Export brief'}).click();
assert.equal((await download).suggestedFilename(),'second-feature-programme.md');
await page.getByRole('button',{name:'Film library',exact:true}).click();
await page.getByRole('button',{name:'Add a film',exact:true}).click();
await page.getByLabel('Film title',{exact:true}).fill('Test Feature');
await page.getByLabel('Director',{exact:true}).fill('Test Director');
await page.getByRole('button',{name:'Add to library'}).click();
await page.getByRole('heading',{name:'Test Feature',exact:true}).waitFor();
await page.reload({waitUntil:'networkidle'});
assert.equal(await page.locator('body').evaluate(()=>JSON.parse(localStorage.getItem('second-feature-workspace-v1')).title),'A night to remember');
await page.getByRole('button',{name:'Reset brief',exact:true}).click();
await page.getByRole('button',{name:'Programming desk',exact:true}).click();
await page.locator('#runtime').fill('160');
await page.getByRole('heading',{name:'No feasible pairing.'}).waitFor();
await page.locator('#runtime').fill('240');
for(const width of [1440,1024,768,390]){
 await page.setViewportSize({width,height:950});
 await page.screenshot({path:`test-results/second-feature-${width}.png`,fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 assert.equal(overflow,false,`Horizontal overflow at ${width}`);
}
await page.emulateMedia({reducedMotion:'reduce'});
await page.getByRole('button',{name:'Inspect evidence',exact:true}).click();
await page.getByRole('heading',{name:'Show your working.'}).waitFor();
await page.keyboard.press('Escape');
assert.deepEqual(errors,[]);
console.log(JSON.stringify({passed:true,checks:['evidence modal','Escape focus return','replanning','strategy','editable brief','download','add film','persistence','empty feasibility state','responsive 1440/1024/768/390','reduced motion'],pageErrors:errors}));
await browser.close();
