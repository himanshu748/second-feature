import {mkdirSync} from 'node:fs';
mkdirSync('test-results',{recursive:true});
import {chromium,expect} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/#/workspace',{waitUntil:'networkidle'});
await expect(page.getByRole('button',{name:'Get Qloo recommendations',exact:true})).toBeEnabled();
await page.getByRole('button',{name:'Get Qloo recommendations',exact:true}).click();
await expect(page.locator('.companion-card h3')).toHaveCount(1,{timeout:120000});
const first=await page.locator('.companion-card h3').innerText();
await expect(page.locator('.data-tag.live').first()).toContainText('QLOO');
const partners=await page.locator('.partner-card').count();assert.ok(partners>0,'Live place results should be rendered');
await page.getByRole('button',{name:'Inspect evidence',exact:true}).click();
await expect(page.locator('.evidence-entity')).toContainText('Qloo entity:');
await page.getByRole('heading',{name:'Show your working.'}).waitFor();
await page.keyboard.press('Escape');
await page.getByRole('button',{name:'Film unavailable? Re-plan',exact:true}).click();
await expect(page.locator('.companion-card h3')).toHaveCount(1,{timeout:120000});
await expect(page.locator('.companion-card h3')).not.toHaveText(first,{timeout:120000});
const second=await page.locator('.companion-card h3').innerText();assert.notEqual(first,second);
await page.locator('h1').click();
await page.screenshot({path:'test-results/second-feature-live.png',fullPage:true});
await page.getByRole('button',{name:'Review event brief',exact:true}).click();
await expect(page.locator('.document-meta')).toContainText('LIVE QLOO EVIDENCE');
await page.screenshot({path:'test-results/second-feature-live-brief.png',fullPage:true});
assert.deepEqual(errors,[]);
console.log(JSON.stringify({passed:true,checks:['live mode','live movie evidence','live place prospects','Qloo entity provenance','exclusion replans with actual evidence','live event brief'],partnerCount:partners,pageErrors:errors}));
await browser.close();
